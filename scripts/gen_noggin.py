"""
gen_noggin.py: builds src/ui/noggin/nogginArt.ts from design/noggin/noggin.py.

The character is never redrawn by hand (CLAUDE.md). This script calls the
locked drawing code, then slims the polyline paths (Ramer-Douglas-Peucker at a
sub-pixel tolerance) so the app bundle stays small and cheap Android phones
render it quickly. The shapes are unchanged at any on-screen size.

Usage:  python3 scripts/gen_noggin.py           (or: npm run gen:noggin)
"""
import importlib.util
import math
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "design", "noggin", "noggin.py")
OUT = os.path.join(ROOT, "src", "ui", "noggin", "nogginArt.ts")
TOLERANCE = 0.08  # drawing units; the body is ~270 units wide

spec = importlib.util.spec_from_file_location("noggin", SRC)
noggin = importlib.util.module_from_spec(spec)
spec.loader.exec_module(noggin)


def rdp(points, eps):
    if len(points) < 3:
        return points
    (x0, y0), (x1, y1) = points[0], points[-1]
    dx, dy = x1 - x0, y1 - y0
    L = math.hypot(dx, dy)
    best, idx = -1.0, 0
    for i in range(1, len(points) - 1):
        px, py = points[i]
        d = abs(dy * px - dx * py + x1 * y0 - y1 * x0) / L if L else math.hypot(px - x0, py - y0)
        if d > best:
            best, idx = d, i
    if best > eps:
        return rdp(points[: idx + 1], eps)[:-1] + rdp(points[idx:], eps)
    return [points[0], points[-1]]


def slim_path(d):
    nums = [float(v) for v in re.findall(r"-?\d+(?:\.\d+)?", d)]
    pts = list(zip(nums[0::2], nums[1::2]))
    if len(pts) < 8:
        return d
    # Split closed rings at their farthest point so RDP keeps both halves.
    far = max(range(len(pts)), key=lambda i: math.hypot(pts[i][0] - pts[0][0], pts[i][1] - pts[0][1]))
    a = rdp(pts[: far + 1], TOLERANCE)
    b = rdp(pts[far:] + [pts[0]], TOLERANCE)
    ring = a[:-1] + b[:-1]
    return "M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in ring) + " Z"


def slim(svg):
    return re.sub(r'd="(M[^"]+Z)"', lambda m: f'd="{slim_path(m.group(1))}"', svg)


out = [
    "// Generated by scripts/gen_noggin.py from design/noggin/noggin.py. Do not edit by hand.",
    "// Locked design D2; see docs/noggin-character.md.",
    "",
    "export type Expression = " + " | ".join(f"'{e}'" for e in noggin.EXPRESSIONS) + ";",
    "",
    "export const NOGGIN_VIEWBOX = { x: 30, y: 100, width: 300, height: 255 };",
    "",
    "export const NOGGIN_SVG: Record<Expression, string> = {",
]
before = after = 0
for e in noggin.EXPRESSIONS:
    svg = noggin.draw(e)
    small = slim(svg)
    before += len(svg)
    after += len(small)
    out.append(f"  {e}: {small!r},")
out.append("};")
out.append("")

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w") as f:
    f.write("\n".join(out))
print(f"wrote {os.path.relpath(OUT, ROOT)}: {before // 1024} KB -> {after // 1024} KB")
